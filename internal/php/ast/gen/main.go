package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
)

func main() {
	out, err := Generate("ast.go")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("children_generated.go", out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var interfaces = map[string]bool{"Node": true, "Expr": true, "Stmt": true, "Member": true, "Type": true}

func Generate(path string) ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	nodes := map[string]*ast.StructType{}
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok {
				continue
			}
			if st, ok := ts.Type.(*ast.StructType); ok && embedsSpan(st) {
				nodes[ts.Name.Name] = st
			}
		}
	}
	names := make([]string, 0, len(nodes))
	for name := range nodes {
		names = append(names, name)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage ast\n\nfunc Children(n Node, visit func(Node)) {\n\tswitch n := n.(type) {\n")
	for _, name := range names {
		var body bytes.Buffer
		for _, field := range nodes[name].Fields.List {
			for _, ident := range field.Names {
				writeField(&body, ident.Name, field.Type, nodes)
			}
		}
		if body.Len() == 0 {
			continue
		}
		fmt.Fprintf(&b, "\tcase *%s:\n%s", name, body.String())
	}
	b.WriteString("\t}\n}\n")
	return format.Source(b.Bytes())
}

func embedsSpan(st *ast.StructType) bool {
	for _, field := range st.Fields.List {
		if ident, ok := field.Type.(*ast.Ident); ok && len(field.Names) == 0 && ident.Name == "Span" {
			return true
		}
	}
	return false
}

func isNode(t ast.Expr, nodes map[string]*ast.StructType) bool {
	switch t := t.(type) {
	case *ast.Ident:
		return interfaces[t.Name]
	case *ast.StarExpr:
		ident, ok := t.X.(*ast.Ident)
		return ok && nodes[ident.Name] != nil
	}
	return false
}

func writeField(b *bytes.Buffer, name string, t ast.Expr, nodes map[string]*ast.StructType) {
	if slice, ok := t.(*ast.ArrayType); ok && isNode(slice.Elt, nodes) {
		fmt.Fprintf(b, "\t\tfor _, c := range n.%s {\n\t\t\tif c != nil {\n\t\t\t\tvisit(c)\n\t\t\t}\n\t\t}\n", name)
		return
	}
	if isNode(t, nodes) {
		fmt.Fprintf(b, "\t\tif n.%s != nil {\n\t\t\tvisit(n.%s)\n\t\t}\n", name, name)
	}
}
