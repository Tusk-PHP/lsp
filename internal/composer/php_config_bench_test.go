package composer

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeBenchFile(b *testing.B, path, content string) {
	b.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		b.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		b.Fatal(err)
	}
}

func BenchmarkAppendComposerAutoloadFiles(b *testing.B) {
	root := b.TempDir()
	var src strings.Builder
	src.WriteString("<?php\n\n// autoload_files.php @generated by Composer\n\n$vendorDir = dirname(__DIR__);\n$baseDir = dirname($vendorDir);\n\nreturn array(\n")
	for i := range 80 {
		fmt.Fprintf(&src, "    '%032x' => $vendorDir . '/vendor%d/package%d/src/helpers.php',\n", i, i, i)
	}
	src.WriteString("    'app' => $baseDir . '/app/helpers.php',\n);\n")
	writeBenchFile(b, filepath.Join(root, "vendor", "composer", "autoload_files.php"), src.String())
	b.ReportAllocs()
	for b.Loop() {
		if got := appendComposerAutoloadFiles(nil, root); len(got) != 81 {
			b.Fatalf("%d files", len(got))
		}
	}
}

func BenchmarkSymfonyBundlePackages(b *testing.B) {
	root := b.TempDir()
	var src strings.Builder
	src.WriteString("<?php\n\nreturn [\n")
	var installed strings.Builder
	installed.WriteString(`{"packages": [`)
	for i := range 30 {
		fmt.Fprintf(&src, "    Vendor%d\\Bundle\\Vendor%dBundle::class => ['all' => true],\n", i, i)
		if i > 0 {
			installed.WriteString(",")
		}
		fmt.Fprintf(&installed, `{"name": "vendor%d/bundle", "install-path": "../vendor%d/bundle", "autoload": {"psr-4": {"Vendor%d\\Bundle\\": "src/"}}}`, i, i, i)
	}
	src.WriteString("];\n")
	installed.WriteString("]}")
	writeBenchFile(b, filepath.Join(root, "config", "bundles.php"), src.String())
	writeBenchFile(b, filepath.Join(root, "vendor", "composer", "installed.json"), installed.String())
	b.ReportAllocs()
	for b.Loop() {
		if got := SymfonyBundlePackages(root); len(got) != 30 {
			b.Fatalf("%d packages", len(got))
		}
	}
}
