package composer

import (
	"os"
	"path/filepath"
	"runtime"
	"testing"
)

func testdataPath() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "testdata", "project")
}

func TestGetAutoloadPaths(t *testing.T) {
	root := testdataPath()
	entries := GetAutoloadPaths(root)

	if len(entries) == 0 {
		t.Fatal("expected autoload entries, got none")
	}

	var appEntry, testsEntry, vendorEntry *AutoloadEntry
	for i := range entries {
		switch entries[i].Namespace {
		case "App":
			appEntry = &entries[i]
		case "Tests":
			testsEntry = &entries[i]
		case "Monolog":
			vendorEntry = &entries[i]
		}
	}

	t.Run("project autoload", func(t *testing.T) {
		if appEntry == nil {
			t.Fatal("missing App\\ autoload entry")
		}
		if appEntry.IsVendor {
			t.Error("App\\ should not be marked as vendor")
		}
		if !filepath.IsAbs(appEntry.Path) {
			t.Errorf("expected absolute path, got %q", appEntry.Path)
		}
	})

	t.Run("project autoload-dev", func(t *testing.T) {
		if testsEntry == nil {
			t.Fatal("missing Tests\\ autoload-dev entry")
		}
		if testsEntry.IsVendor {
			t.Error("Tests\\ should not be marked as vendor")
		}
	})

	t.Run("vendor autoload", func(t *testing.T) {
		if vendorEntry == nil {
			t.Fatal("missing Monolog\\ vendor autoload entry")
		}
		if !vendorEntry.IsVendor {
			t.Error("Monolog\\ should be marked as vendor")
		}
		if !filepath.IsAbs(vendorEntry.Path) {
			t.Errorf("expected absolute path, got %q", vendorEntry.Path)
		}
	})
}

func TestGetAutoloadFiles(t *testing.T) {
	root := testdataPath()
	entries := GetAutoloadPaths(root)

	var projectFile, vendorFile *AutoloadEntry
	for i := range entries {
		if !entries[i].IsFile {
			continue
		}
		if !entries[i].IsVendor {
			projectFile = &entries[i]
		} else {
			vendorFile = &entries[i]
		}
	}

	t.Run("project autoload files", func(t *testing.T) {
		if projectFile == nil {
			t.Fatal("missing project autoload.files entry")
		}
		if projectFile.IsVendor {
			t.Error("project file should not be marked as vendor")
		}
		if projectFile.Namespace != "" {
			t.Errorf("file entries should have empty namespace, got %q", projectFile.Namespace)
		}
		if !filepath.IsAbs(projectFile.Path) {
			t.Errorf("expected absolute path, got %q", projectFile.Path)
		}
	})

	t.Run("vendor autoload files", func(t *testing.T) {
		if vendorFile == nil {
			t.Fatal("missing vendor autoload.files entry")
		}
		if !vendorFile.IsVendor {
			t.Error("vendor file should be marked as vendor")
		}
		if vendorFile.Namespace != "" {
			t.Errorf("file entries should have empty namespace, got %q", vendorFile.Namespace)
		}
	})
}

func TestGetAutoloadFilesFromComposerGeneratedFile(t *testing.T) {
	root := t.TempDir()
	composerDir := filepath.Join(root, "vendor", "composer")
	if err := os.MkdirAll(composerDir, 0755); err != nil {
		t.Fatal(err)
	}
	content := `<?php
// autoload_files.php @generated by Composer
$vendorDir = dirname(__DIR__);
$baseDir = dirname($vendorDir);

return array(
    'a' => $vendorDir . '/laravel/framework/src/Illuminate/Support/helpers.php',
    'b' => $baseDir . '/app/helpers.php',
);
`
	if err := os.WriteFile(filepath.Join(composerDir, "autoload_files.php"), []byte(content), 0644); err != nil {
		t.Fatal(err)
	}

	entries := GetAutoloadPaths(root)
	var vendorFile, projectFile *AutoloadEntry
	for i := range entries {
		if entries[i].Path == filepath.Join(root, "vendor", "laravel", "framework", "src", "Illuminate", "Support", "helpers.php") {
			vendorFile = &entries[i]
		}
		if entries[i].Path == filepath.Join(root, "app", "helpers.php") {
			projectFile = &entries[i]
		}
	}
	if vendorFile == nil || !vendorFile.IsFile || !vendorFile.IsVendor {
		t.Fatalf("expected generated vendor helper file entry, got %#v", vendorFile)
	}
	if projectFile == nil || !projectFile.IsFile || projectFile.IsVendor {
		t.Fatalf("expected generated project helper file entry, got %#v", projectFile)
	}
}

func TestGetAutoloadPathsMissing(t *testing.T) {
	entries := GetAutoloadPaths("/nonexistent/path")
	if len(entries) != 0 {
		t.Errorf("expected 0 entries for missing path, got %d", len(entries))
	}
}

func TestGetAutoloadPathsNoVendor(t *testing.T) {
	// testdata/project has a composer.json but if we point to a subdir without one
	root := testdataPath()
	entries := GetAutoloadPaths(filepath.Join(root, "src"))
	// Should return 0 since src/ has no composer.json
	if len(entries) != 0 {
		t.Errorf("expected 0 entries for dir without composer.json, got %d", len(entries))
	}
}
